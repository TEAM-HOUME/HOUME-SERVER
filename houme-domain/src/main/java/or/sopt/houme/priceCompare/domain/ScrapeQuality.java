package or.sopt.houme.priceCompare.domain;

/**
 * 스크래핑 결과의 완성도. 파싱은 "전부 성공/전부 실패"가 아니라 부분 성공이 정상이므로,
 * 후속 파이프라인(이미지 검색 스킵 여부 등)과 프론트 에러 정책이 이 값으로 분기한다.
 */
public enum ScrapeQuality {

    /** 상품명·이미지·브랜드·가격을 모두 확보. */
    FULL,

    /** 상품명과 이미지는 확보. 브랜드/가격 중 일부 누락. */
    PARTIAL,

    /** 상품명·이미지 중 하나만 확보. 검색은 가능하나 정확도가 낮다. */
    MINIMAL
}
